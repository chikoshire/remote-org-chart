/** Normalize world-atlas / UN M49 numeric country id. */
export function normalizeNumericId(id: string | number | null | undefined): string | null {
  if (id == null) return null;
  const raw = String(id).trim();
  if (!/^\d+$/.test(raw)) return null;
  return raw.padStart(3, "0");
}

export function alphaToNumericId(code: string | null | undefined): string | null {
  if (!code?.trim()) return null;
  return ALPHA_TO_NUMERIC[code.trim().toUpperCase()] ?? null;
}
